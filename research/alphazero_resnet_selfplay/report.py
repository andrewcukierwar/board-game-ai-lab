# Tables ---------------------------------------------------------------------------------------

def f(value, digits=3):
    if value is None:
        return '—'
    return f'{value:.{digits}f}' if isinstance(value, float) else str(value)


def signed(value, digits=3):
    return '—' if value is None else f'{value:+.{digits}f}'


def interval(c, digits=3):
    return f'{signed(c["difference"], digits)} [{signed(c["interval95"][0], digits)}, {signed(c["interval95"][1], digits)}]'


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(lines) + '\n'


def contrast_table(block, metrics=None):
    rows = []
    for name, c in block.items():
        if metrics and name not in metrics:
            continue
        seeds = [interval(c['per_seed'][str(s)]) for s in SEEDS]
        rows.append([name, 'higher' if c['higher_is_better'] else 'lower', *seeds, interval(c['pooled']), c['verdict']])
    return table(['Measure', 'Better is', *(f'Seed {s}' for s in SEEDS), 'Pooled', 'Rule'], rows)


