# Figures --------------------------------------------------------------------------------------

def marker(name, x, y, tip):
    title = f'<title>{tip}</title>'
    if name == 'cnn':
        return f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4.5" fill="{COLOR[name]}" stroke="{SURFACE}" stroke-width="2">{title}</circle>'
    return (f'<rect x="{x - 4.2:.1f}" y="{y - 4.2:.1f}" width="8.4" height="8.4" fill="{COLOR[name]}" stroke="{SURFACE}" '
            f'stroke-width="2">{title}</rect>')


def panel(x0, y0, width, height, title, series, ymin, ymax, xmax, xlabel, ylabel, digits=2, baseline=None):
    """One small multiple: shared axis style, 2px lines, ringed markers, direct labels at the line ends."""
    sx = lambda x: x0 + width * x / xmax
    sy = lambda y: y0 + height * (1 - (y - ymin) / (ymax - ymin))
    out = [f'<text x="{x0}" y="{y0 - 12}" {FONT} font-size="12.5" font-weight="600" fill="{INK}">{title}</text>']
    span = ymax - ymin
    digits = max(digits, 0 if span >= 8 else 1 if span >= 0.8 else 2 if span >= 0.08 else 3 if span >= 0.008 else 4)
    xdigits = 0 if xmax >= 8 else 1 if xmax >= 0.8 else 2
    for i in range(5):
        value = ymin + (ymax - ymin) * i / 4
        out.append(f'<line x1="{x0}" x2="{x0 + width}" y1="{sy(value):.1f}" y2="{sy(value):.1f}" stroke="{GRID}" stroke-width="1"/>')
        out.append(f'<text x="{x0 - 7}" y="{sy(value) + 3.5:.1f}" {FONT} font-size="10.5" fill="{MUTED}" text-anchor="end">{value:.{digits}f}</text>')
    ticks = list(range(int(xmax) + 1)) if xmax == int(xmax) and xmax <= 12 else [xmax * i / 4 for i in range(5)]
    for value in ticks:
        out.append(f'<text x="{sx(value):.1f}" y="{y0 + height + 15}" {FONT} font-size="10.5" fill="{MUTED}" text-anchor="middle">{value:.{xdigits}f}</text>')
    out.append(f'<text x="{x0 + width / 2}" y="{y0 + height + 31}" {FONT} font-size="10.5" fill="{MUTED}" text-anchor="middle">{xlabel}</text>')
    out.append(f'<text x="{x0 - 42}" y="{y0 + height / 2}" {FONT} font-size="10.5" fill="{MUTED}" text-anchor="middle" '
               f'transform="rotate(-90 {x0 - 42} {y0 + height / 2})">{ylabel}</text>')
    if baseline is not None:
        value, text = baseline
        out.append(f'<line x1="{x0}" x2="{x0 + width}" y1="{sy(value):.1f}" y2="{sy(value):.1f}" stroke="{MUTED}" stroke-width="1" stroke-dasharray="4 3"/>')
        out.append(f'<text x="{x0 + 4}" y="{sy(value) - 4:.1f}" {FONT} font-size="10" fill="{MUTED}">{text}</text>')
    ends = []
    for name, points in series:
        path = ' '.join(f'{"M" if i == 0 else "L"}{sx(x):.1f},{sy(y):.1f}' for i, (x, y, _) in enumerate(points))
        out.append(f'<path d="{path}" fill="none" stroke="{COLOR[name]}" stroke-width="2" stroke-linejoin="round"/>')
        out += [marker(name, sx(x), sy(y), f'{TITLE[name]}, {tip}: {y:.3f}') for x, y, tip in points]
        ends.append([sy(points[-1][1]), name, sx(points[-1][0])])
    ends.sort()
    if len(ends) == 2 and ends[1][0] - ends[0][0] < 13:   # keep the two direct labels from colliding
        middle = (ends[0][0] + ends[1][0]) / 2
        ends[0][0], ends[1][0] = middle - 6.5, middle + 6.5
    for y, name, x in ends:
        out.append(f'<text x="{x + 9:.1f}" y="{y + 3.5:.1f}" {FONT} font-size="10.5" fill="{INK}">{TITLE[name]}</text>')
    return '\n'.join(out)


def legend(x, y):
    out = []
    for i, name in enumerate(NAMES):
        out.append(marker(name, x + 110 * i, y, TITLE[name]))
        out.append(f'<text x="{x + 110 * i + 10}" y="{y + 4}" {FONT} font-size="11.5" fill="{INK}">{TITLE[name]}</text>')
    return '\n'.join(out)


def figure(title, subtitle, rows):
    """rows: list of rows of panel specs (dicts); two columns (one per seed)."""
    width, height, left, top, pw, ph, gx, gy = 940, 96 + 250 * len(rows), 78, 96, 290, 150, 170, 100
    body = [f'<rect width="{width}" height="{height}" fill="{SURFACE}"/>',
            f'<text x="24" y="30" {FONT} font-size="15" font-weight="600" fill="{INK}">{title}</text>',
            f'<text x="24" y="49" {FONT} font-size="11.5" fill="{MUTED}">{subtitle}</text>', legend(30, 66)]
    for r, row in enumerate(rows):
        for c, spec in enumerate(row):
            body.append(panel(left + c * (pw + gx), top + 14 + r * (ph + gy), pw, ph, **spec))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
            f'role="img" aria-label="{title}">\n' + '\n'.join(body) + '\n</svg>\n')


def nice(value):
    """Smallest axis maximum of four round steps that covers the value."""
    import math
    magnitude = 10 ** math.floor(math.log10(value / 4))
    return 4 * next(m * magnitude for m in (1, 2, 2.5, 5, 10) if 4 * m * magnitude >= value)


def scale(values, pad=0.08, floor=None, ceiling=None):
    low, high = min(values), max(values)
    span = (high - low) or 1.0
    low, high = low - pad * span, high + pad * span
    return (low if floor is None else max(floor, low)), (high if ceiling is None else min(ceiling, high))


def figures(a, directory):
    arms, table = a['computation']['arms'], a['trajectories']
    compute = {label: [0.0] + [g['cumulative']['compute_seconds'] for g in arm['generations']] for label, arm in arms.items()}
    xmax_compute = nice(max(v[-1] for v in compute.values()))
    xmax_games = nice(max(r['cumulative_games'] for per in table.values() for r in per))
    generations = len(next(iter(table.values()))) - 1

    def series(seed, getter, axis):
        result = []
        for name in NAMES:
            label = arm_label(seed, name)
            points = []
            for row in table[label]:
                value = getter(row)
                if value is not None:
                    x = dict(compute=compute[label][row['generation']], games=row['cumulative_games'],
                             generation=row['generation'])[axis]
                    points.append((x, value, f'generation {row["generation"]}'))
            result.append((name, points))
        return result

    def row(caption, getter, axis, ylabel, digits=2, floor=None, ceiling=None, baseline=None, fixed=None):
        per_seed = {s: series(s, getter, axis) for s in SEEDS}
        values = [y for ss in per_seed.values() for _, pts in ss for _, y, _ in pts] + ([baseline[0]] if baseline else [])
        ymin, ymax = fixed or scale(values, floor=floor, ceiling=ceiling)
        xmax, xlabel = dict(compute=(xmax_compute, 'cumulative self-play + update seconds'),
                            games=(xmax_games, 'cumulative self-play games'),
                            generation=(generations, 'generation'))[axis]
        return [dict(title=f'{caption} — seed {s}', series=per_seed[s], ymin=ymin, ymax=ymax, xmax=xmax, xlabel=xlabel,
                     ylabel=ylabel, digits=digits, baseline=baseline) for s in SEEDS]
    match = lambda r: r['match']['score'] if 'match' in r else None
    raw = lambda key: (lambda r: r['raw'][key] if 'raw' in r else None)
    puct = lambda key: (lambda r: r['puct'][key] if 'puct' in r else None)
    zero = next(r['raw']['solved_constant_zero_value_mse'] for per in table.values() for r in per if 'raw' in r)
    loss = lambda key: (lambda r: arms[r['_label']]['generations'][r['generation'] - 1][key] if r['generation'] else None)
    for label, per in table.items():
        for r in per:
            r['_label'] = label
    outputs = {
        'figure-strength.svg': figure(
            'Match score against reference negamax depth 3', 'Raw PUCT, 256 simulations, 80 games per point. Top: by '
            'realized training computation. Bottom: by cumulative games.',
            [row('Score', match, 'compute', 'match score', fixed=(0.0, 1.0), baseline=(0.5, 'even')),
             row('Score', match, 'games', 'match score', fixed=(0.0, 1.0), baseline=(0.5, 'even'))]),
        'figure-tactics.svg': figure(
            'Tactical reliability on tactical200', 'Safe-response accuracy, raw policy (every generation) and raw PUCT '
            '(generations 0, 2, 4, 6), and PUCT immediate-win accuracy.',
            [row('Raw policy, safe response', raw('tactical_policy_safe_response'), 'compute', 'accuracy', floor=0, ceiling=1),
             row('Raw PUCT, safe response', puct('tactical_puct_safe_response'), 'compute', 'accuracy', floor=0, ceiling=1),
             row('Raw PUCT, immediate win', puct('tactical_puct_immediate_win'), 'compute', 'accuracy', floor=0, ceiling=1)]),
        'figure-policy-value.svg': figure(
            'Raw network against exact labels on solved300', 'Optimal-action-set cross-entropy (lower is better) and '
            'exact-value MSE with the constant-zero baseline.',
            [row('Policy cross-entropy', raw('solved_optimal_set_ce'), 'compute', 'nats', floor=0),
             row('Optimal-action accuracy', raw('solved_optimal_accuracy'), 'compute', 'accuracy', floor=0, ceiling=1),
             row('Exact-value MSE', raw('solved_exact_value_mse'), 'compute', 'MSE', floor=0, baseline=(zero, 'constant zero'))]),
        'figure-training.svg': figure(
            'Training losses on self-generated targets', 'Mean over each generation\'s updates. Diagnostic only: the '
            'two architectures are fitting different data.',
            [row('Policy loss', loss('policy_loss'), 'generation', 'cross-entropy', floor=0),
             row('Value loss', loss('value_loss'), 'generation', 'MSE', floor=0)])}
    directory.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        (directory / name).write_text(text)
    return sorted(outputs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--smoke', action='store_true')
    args = parser.parse_args()
    source = (OUTPUT / 'smoke/analysis.json') if args.smoke else (RESULTS / 'analysis.json')
    target = (OUTPUT / 'smoke/report') if args.smoke else RESULTS
    analysis = read(source)
    target.mkdir(parents=True, exist_ok=True)
    (target / 'tables.md').write_text(tables(analysis))
    print(figures(analysis, target), len(tables(analysis).splitlines()), 'table lines')


if __name__ == '__main__':
    main()
